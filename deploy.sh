#!/bin/bash
# Публикация на GitHub Pages: проставляет свежую метку версии у скриптов и
# стилей (иначе телефон до 10 минут держит в кэше старые файлы вперемешку
# с новыми), коммитит и отправляет в main.
# Запуск: ./deploy.sh "что изменилось"
set -e
cd "$(dirname "$0")"
v=$(date +%Y%m%d%H%M%S)
sed -i '' -E "s/\?v=[0-9]+\"/?v=$v\"/g" index.html
git add -A
git commit -qm "${1:-Обновление}"
git push -q
echo "Опубликовано, версия $v. Сайт обновится примерно через минуту."
